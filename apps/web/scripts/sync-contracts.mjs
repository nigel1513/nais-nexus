#!/usr/bin/env node
// Generates src/generated/contracts.ts from NAIS_PRD/contracts (error codes + top-level enum schemas).
// Usage: node scripts/sync-contracts.mjs [--check]   (--check exits 1 when the committed file is stale)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../../..");
const contracts = path.join(root, "NAIS_PRD", "contracts");
const target = path.resolve(here, "../src/generated/contracts.ts");

const codes = JSON.parse(readFileSync(path.join(contracts, "error_codes.json"), "utf8")).codes;
const openapi = YAML.parse(readFileSync(path.join(contracts, "openapi.yaml"), "utf8"));
const enums = Object.fromEntries(
  Object.entries(openapi.components.schemas)
    .filter(([, schema]) => Array.isArray(schema.enum))
    .map(([name, schema]) => [name, schema.enum]),
);

const out =
  "// GENERATED by apps/web/scripts/sync-contracts.mjs from NAIS_PRD/contracts - do not edit.\n\n" +
  `export const ERROR_HTTP: Record<string, number> = ${JSON.stringify(Object.fromEntries(codes.map((c) => [c.code, c.http])), null, 2)};\n\n` +
  `export const ERROR_CODES = ${JSON.stringify(codes.map((c) => c.code), null, 2)} as const;\n\n` +
  `export const ENUMS = ${JSON.stringify(enums, null, 2)} as const;\n`;

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.error("apps/web/src/generated/contracts.ts is stale; run: pnpm --filter @nais/web contracts:sync");
    process.exit(1);
  }
  console.log("web contracts up to date");
} else {
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, out);
  console.log("wrote", path.relative(root, target));
}
